test("performance conformance: this build can still read the work it already delivered", () => {
  if (process.env.HV_PERFORMANCE_RECORDS_REFRESH?.trim()) {
    const built = buildRecords();
    mkdirSync(dirname(RECORDS_PATH), { recursive: true });
    const staging = RECORDS_PATH + ".tmp";
    writeFileSync(staging, JSON.stringify(built, null, 2) + "\n");
    renameSync(staging, RECORDS_PATH);
  }
  const golden = JSON.parse(readFileSync(RECORDS_PATH, "utf8")) as GoldenRecords;
  expect(golden.schema).toBe("hv-performance-golden-records/1");

  // Each record goes through the validator that reads it back in production. A revision edit
  // fails here, with the message an operator would see on a restore.
  for (const [name, line, expectedRevision] of [
    ["audioLineV1", golden.audioLineV1, CARTESIA_AUDIO_CAPABILITY.revision],
    ["audioLineV3", golden.audioLineV3, CARTESIA_PHRASE_CAPABILITY.revision],
    ["audioLineV4", golden.audioLineV4, AZURE_AUDIO_CAPABILITY.revision],
    ["audioLineV5", golden.audioLineV5, CARTESIA_MULTILINGUAL_CAPABILITY.revision],
  ] as const) {
    expect({ name, revision: line.capabilityRevision }).toEqual({ name, revision: expectedRevision });
    expect(validateAudioLinePlan(line)).toEqual(line);
  }
  expect(validateAudioDelivery(golden.audioDelivery)).toEqual(golden.audioDelivery);
  expect(validateAudioDelivery(golden.azureDelivery)).toEqual(golden.azureDelivery);
  expect(golden.azureDelivery.schema).toBe("hv-audio-line-delivery/2");
  expect(() => validateAudioIntent(golden.audioIntent, golden.audioLineV1)).not.toThrow();
  expect(() => validateAudioIntent(golden.azureIntent, golden.audioLineV4)).not.toThrow();
  expect(golden.azureIntent.schema).toBe("hv-audio-dispatch/2");
  // The two policy records are NOT revision tripwires and are not claimed to be.
  // validateAudioPolicy resolves no capability: it re-derives permissionRevision, priceRevision,
  // the record revision and the model string from the live AZURE_AUDIO_MODEL / CARTESIA_MODEL
  // constants and hash-compares. The capability-model comparison lives in audioTakePlan, which
  // needs a job and a screenplay and is exercised by the PostgreSQL-backed storage suites. They
  // are committed here because a model-constant edit is its own hazard, and listed in the pins
  // evidence's unpinnedReadBackPaths so nobody reads them as revision coverage.
  // `now` is deliberately omitted — a golden fixture with a fixed validity window must not become
  // a time bomb that turns CI red on a date nobody chose.
  expect(validateAudioPolicy(golden.audioPolicyCartesia)).toEqual(golden.audioPolicyCartesia);
  expect(validateAudioPolicy(golden.audioPolicyAzure)).toEqual(golden.audioPolicyAzure);
  expect(validateLipSyncPolicy(golden.lipSyncPolicy)).toEqual(golden.lipSyncPolicy);
  expect(golden.lipSyncPolicy.capabilityRevision).toBe(LIPSYNC_CAPABILITY.revision);
  expect(() => validateLipSyncDelivery(golden.lipSyncDelivery)).not.toThrow();

  // The fixture carries no credential, no destination and no host path. Two URIs do appear and
  // are allowed by name rather than by loosening the pattern: the Azure line's provider transcript
  // is SSML, whose XML namespaces are part of the format the adapter generates. They are namespace
  // identifiers, not endpoints — nothing fetches them.
  const text = readFileSync(RECORDS_PATH, "utf8");
  const SSML_NAMESPACES = ["http://www.w3.org/2001/10/synthesis", "https://www.w3.org/2001/mstts"];
  let scrubbed = text;
  for (const namespace of SSML_NAMESPACES) {
    expect(text).toContain(namespace);
    scrubbed = scrubbed.split(namespace).join("<ssml-namespace>");
  }
  for (const pattern of [/:\/\//, /API_KEY/i, /\/home\//, /\/Users\//, /\/tmp\//, /cartesia\.ai/, /\.microsoft\.com/, /sync\.so/]) {
    expect(scrubbed).not.toMatch(pattern);
  }
  record({ name: "golden-records", pairs: 12, passed: 12, skipped: 0 });
});

test("performance conformance: a moved revision is refused, not silently accepted", () => {
  const golden = JSON.parse(readFileSync(RECORDS_PATH, "utf8")) as GoldenRecords;
  // What a revision edit would actually do to finished work. Substituting any other live revision
  // into a delivered record makes the record unreadable — which is the same outcome as this build
  // no longer being able to produce the revision the record pins.
  const { revision: _r, ...data } = { ...golden.audioLineV1, capabilityRevision: CARTESIA_PHRASE_CAPABILITY.revision };
  expect(() => validateAudioLinePlan({ ...data, revision: contentHash(data) } as never)).toThrow();
  expect(() => validateLipSyncDelivery({ ...golden.lipSyncDelivery, capabilityRevision: CARTESIA_AUDIO_CAPABILITY.revision })).toThrow();
  const lip = { ...golden.lipSyncPolicy, capabilityRevision: CARTESIA_AUDIO_CAPABILITY.revision };
  expect(() => validateLipSyncPolicy(lip)).toThrow();
  record({ name: "moved-revision-refused", pairs: 3, passed: 3, skipped: 0 });
});

