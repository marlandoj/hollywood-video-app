test("performance conformance: schema is inside every performance hash and outside the video hash", () => {
  for (const value of [...AUDIO_CAPABILITIES, LIPSYNC_CAPABILITY]) {
    const { revision, ...definition } = value as Record<string, unknown> & { revision: string };
    // The definition that was hashed includes the schema string.
    expect(contentHash(definition)).toBe(revision);
    const { schema: _schema, ...withoutSchema } = definition;
    expect(contentHash(withoutSchema)).not.toBe(revision);
    // Therefore a schema rename alone moves this revision. This is the fact that makes
    // "re-express these as hv-capability/2" non-additive under any lookup shim.
    const renamed = { ...definition, schema: "hv-capability/2" };
    expect(contentHash(renamed)).not.toBe(revision);
  }
  // The video lane is the opposite: capability() hashes a definition with no schema key and
  // adds the literal afterwards, so the video schema string is not in any video revision.
  const snapshot = describeProvider("mock", "final", {}).snapshot;
  const { schema: _vs, revision: _vr, priceVersion: _vp, ...videoDefinition } = snapshot as unknown as Record<string, unknown>;
  expect(contentHash(videoDefinition)).toBe(snapshot.revision);
  record({ name: "hash-shape", pairs: AUDIO_CAPABILITIES.length + 2, passed: AUDIO_CAPABILITIES.length + 2, skipped: 0 });
});

test("performance conformance: the video capability builder cannot express an audio contract", () => {
  const snapshot = describeProvider("mock", "final", {}).snapshot;
  const { schema: _s, revision: _r, priceVersion: _p, ...definition } = snapshot as unknown as Record<string, unknown>;
  // `modality: "audio"` is refused today. Widening that union is a loosening and would be safe,
  // but it buys nothing: capability() also requires output.minWidth/minHeight/maxWidth/maxHeight
  // as integers in [16, 8192], so an audio contract could only be expressed by fabricating
  // dimensions into a content-addressed record — which CLAUDE.md forbids — or by making the whole
  // output block modality-conditional, which is a validator change, not a union widening.
  expect(() => capability({ ...definition, modality: "audio" } as never)).toThrow("Invalid provider capability configuration.");
  const { output } = definition as { output: Record<string, unknown> };
  for (const field of ["minWidth", "minHeight", "maxWidth", "maxHeight"]) expect(typeof output[field]).toBe("number");
  record({ name: "audio-modality-unexpressible", pairs: 5, passed: 5, skipped: 0 });
});

