function validatePins(value: unknown): PinsDocument {
  const document = value as PinsDocument;
  if (!document || typeof document !== "object" || document.schema !== "hv-performance-capability-pins/1") throw new Error("Invalid performance capability pins document.");
  if (!/^\d{4}-\d{2}-\d{2}T[\d:.]+Z$/.test(document.recordedAt)) throw new Error("Invalid performance capability pins document.");
  if (!Array.isArray(document.entries) || !document.entries.length) throw new Error("Invalid performance capability pins document.");
  for (const entry of document.entries) {
    if (!/^[a-f0-9]{64}$/.test(entry.capabilityRevision)) throw new Error("Invalid performance capability pins document.");
    if (entry.paid !== true) throw new Error("Invalid performance capability pins document.");
  }
  if (document.schemaIsInsideTheHash !== true || document.videoSchemaIsOutsideTheHash !== true) throw new Error("Invalid performance capability pins document.");
  if (document.poolAdmitted !== false || document.newProviderSpendUsd !== 0 || document.liveProviderDispatches !== 0) throw new Error("Invalid performance capability pins document.");
  for (const field of ["provesVendorAvailability", "provesVoiceQuality", "provesLipSyncQuality", "provesLivePricing"] as const) {
    if (document[field] !== false) throw new Error("Invalid performance capability pins document.");
  }
  if (!Array.isArray(document.unpinnedReadBackPaths) || !document.unpinnedReadBackPaths.length) throw new Error("Invalid performance capability pins document.");
  // The count of pinned shapes must agree with the list, and must not silently claim the whole
  // surface: fifteen record shapes pin a performance revision and ten of them have a golden record.
  if (document.goldenRecordsCarryingARevisionPin !== document.goldenRecords.length
    || document.goldenRecordsCarryingARevisionPin > document.revisionPinningShapes) throw new Error("Invalid performance capability pins document.");
  return document;
}

