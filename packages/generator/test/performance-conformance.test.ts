  const azureDeliveryAttempt = crypto.randomUUID();
  const azureDelivery = createAudioDelivery(lineV4, azureDeliveryAttempt, AUDIO_PCM,
    [{ text: "Hello", startSec: 0, endSec: 0.5 }], []).report;
  const azureDispatchId = crypto.randomUUID();
