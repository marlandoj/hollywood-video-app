test("performance conformance: nothing was dispatched, no key was read, and no pool exists", () => {
  // The whole proof, and it does not depend on the ambient environment: the stub replaces fetch
  // before any test body runs and was never called. An earlier draft also asserted that the three
  // provider key variables were empty, which was theatre — this suite constructs no adapter, so no
  // key is read either way, and the assertion turned a contributor's exported key into a red run
  // for a reason unrelated to their change.
  expect(fetchCalls).toBe(0);
  // There is no performance pool or admitted plan, deliberately: a pool is a failover set, and
  // this lane forbids failover in code — "No automatic retry, alternate voice, or fallback
  // provider may consume a second reservation." Voice selection is by voice id through an
  // hv-audio-policy record, and admitting a pool would break the three single-heldUsd
  // reservation invariants. That work is HV-022's clause (FULL-SCOPE §P7), not this increment's.
  record({ name: "no-dispatch", pairs: 1, passed: 1, skipped: 0 });
});

test("performance conformance: the pins are committed and re-derived on every run", () => {
  const output = process.env.HV_PERFORMANCE_PINS_EVIDENCE?.trim();
  if (output) {
    const document = validatePins(buildPins());
    mkdirSync(dirname(output), { recursive: true });
    const staging = output + ".tmp";
    writeFileSync(staging, JSON.stringify(document, null, 2) + "\n");
    renameSync(staging, output);
  }

  const text = readFileSync(PINS_PATH, "utf8");
  const document = validatePins(JSON.parse(text));
  // The tripwire. Each recorded revision must equal the revision this build produces; an edit to
  // any capability definition breaks here rather than on a restore months later.
  expect(document.entries.map((entry) => `${entry.lane}:${entry.provider}:${entry.schema}:${entry.capabilityRevision}`).sort())
    .toEqual(PERFORMANCE_REGISTRY.map((entry) => `${entry.lane}:${entry.provider}:${entry.schema}:${entry.capabilityRevision}`).sort());
  expect(document.lanes).toEqual([...PERFORMANCE_LANES]);
  expect(document.checks.map((check) => check.name).sort()).toEqual(
    ["audio-modality-unexpressible", "cross-lane-resolver", "golden-records", "hash-shape",
      "moved-revision-refused", "no-dispatch", "registry-derivation", "revision-is-the-key"],
  );
  // No credential, no destination, no host path. The one 64-hex value that is not a revision is
  // lip-sync's pinned OpenAPI digest, which this file does not record — allowed by name, not by
  // loosening the pattern.
  for (const pattern of [/:\/\//, /API_KEY/i, /\/home\//, /\/Users\//, /\/tmp\//]) expect(text).not.toMatch(pattern);
  const known = new Set(PERFORMANCE_REGISTRY.map((entry) => entry.capabilityRevision));
  for (const hex of text.match(/[a-f0-9]{32,}/g) ?? []) expect({ hex, known: known.has(hex) }).toEqual({ hex, known: true });
  expect(text).not.toContain(LIPSYNC_CAPABILITY.openapiSha256);
  record({ name: "pins-evidence", pairs: PERFORMANCE_REGISTRY.length, passed: PERFORMANCE_REGISTRY.length, skipped: 0 });
});

