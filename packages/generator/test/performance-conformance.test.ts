// The conformance suite FULL-SCOPE §7 already requires of the Voice and Lip-sync
// lanes. §7 lists both in the same candidate matrix as the video adapters and
// holds them to the same rule — "each must pass the adapter conformance suite and
// the studio benchmark before promotion" — and until this file there was no suite
// at all for either.
//
// Why that mattered more than tidiness: nothing anywhere guarded the five
// performance capability revisions. Not one of them appeared as a literal in any
// committed test, fixture or evidence file; every audio test derives its
// expectation from the live constant, so an edit to a capability definition moved
// the test's expectation along with the code and `bun test` stayed green. But
// those revisions are pinned inside *already-delivered* records — line plans,
// dispatch receipts, deliveries, policies — and every validator that reads one
// back re-derives the revision and refuses a mismatch. `validateSnapshot` reaches
// `validateAudioTake` and `validateAudioIntent` from all four snapshot entry
// points, so one moved revision makes every portable archive and every backup
// restore containing an audio take permanently un-importable.
//
// So this suite does two things the video suite already does for its lane:
// it pins the revisions as committed evidence re-derived on every run, and it
// commits golden delivered records that this build must still be able to read.
// A revision edit now fails here, with the message an operator would see, instead
// of passing and failing on a restore.
//
// No capability definition is touched, no adapter is constructed, no key is read,
// and `globalThis.fetch` is replaced by a stub that throws and is asserted never
// to have been called.
