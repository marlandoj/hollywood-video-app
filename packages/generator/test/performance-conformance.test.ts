  revisionPinningShapes: number;
  goldenRecordsCarryingARevisionPin: number;
  additionalRecordsWithoutARevisionPin: string[];
  unpinnedReadBackPaths: { path: string; reason: string; coveredBy: string }[];
  checks: CheckRecord[];
  poolAdmitted: false;
  newProviderSpendUsd: 0;
  liveProviderDispatches: 0;
  provesVendorAvailability: false;
  provesVoiceQuality: false;
  provesLipSyncQuality: false;
  provesLivePricing: false;
